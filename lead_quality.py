def fmt_inr(x):
    if x is None:
        return "—"
    x = int(round(x))
    s = str(abs(x))
    if len(s) > 3:  # Indian grouping 12,34,567
        head, tail = s[:-3], s[-3:]
        head = re.sub(r"(\d)(?=(\d{2})+$)", r"\1,", head)
        s = f"{head},{tail}"
    return ("-" if x < 0 else "") + "₹" + s


