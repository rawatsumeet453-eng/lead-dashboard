def verdict(m: dict, th: dict):
    if m["leads"] < th["low_data_leads"]:
        return "LOW DATA", f"Sirf {m['leads']} leads — quality % pe decision mat lo; CTR/CPM/CPL dekho."
    q, v = m["quality_pct"], m["visit_ratio_pct"]
    if q >= th["scale_quality_pct"]:
        if v >= th["target_visit_ratio_pct"]:
            return "SCALE", f"Quality {q}% + visit ratio {v}% — budget 15-20% badhao (har 3-4 din)."
        return "OPTIMIZE", f"Quality {q}% achhi hai par visit ratio {v}% (<{th['target_visit_ratio_pct']}%) — sales follow-up / visit push check karo."
    if q >= th["optimize_quality_pct"]:
        return "OPTIMIZE", f"Quality {q}% — form questions, placements aur weak ads tighten karo."
    if q >= th["review_quality_pct"]:
        return "REVIEW ADS + AUDIENCE", f"Quality {q}% — creatives aur audience dobara dekho."
    return "PAUSE / FIX", f"Quality {q}% (<{th['review_quality_pct']}%) — pause ya bada fix (form, audience, offer)."


def metrics(df: pd.DataFrame, spend: float, ads_row: dict | None = None) -> dict:
    n = len(df)
    b = df["bucket"].value_counts().to_dict() if n else {}
    k = df["key"].value_counts().to_dict() if n else {}
    visits = k.get("visited", 0) + k.get("booked", 0)
    m = {
        "leads": n,
        "quality": int(b.get("Quality", 0)),
        "quality_pct": pct(b.get("Quality", 0), n),
        "booked": int(k.get("booked", 0)),
        "visited": int(k.get("visited", 0)),
        "site_visits": int(visits),
        "will_visit": int(k.get("will_visit", 0)),
        "visit_ratio_pct": pct(visits, n),
        "followup": int(b.get("Follow-up", 0)),
        "dead": int(b.get("Dead", 0)),
        "not_called": int(b.get("Not Called", 0)),
        "unmapped": int(b.get("Unmapped", 0)),
        "spend": round(float(spend), 2),
        "cpl": money(spend, n),
        "cost_per_quality_lead": money(spend, b.get("Quality", 0)),
        "cost_per_visit": money(spend, visits),
    }
    if ads_row:
        imp, clk = ads_row.get("impressions", 0), ads_row.get("link_clicks", 0)
        m.update({
            "impressions": int(imp), "link_clicks": int(clk), "meta_leads": int(ads_row.get("meta_leads", 0)),
            "ctr_pct": round(clk * 100.0 / imp, 2) if imp else None,
            "cpm": round(spend * 1000.0 / imp) if imp else None,
        })
    return m


def build(client: str, crm_path, ads_path, spend_override, d_from, d_to):
    client_dir = CLIENTS_DIR / client
    if not client_dir.exists():
        sys.exit(f"Client folder nahi mila: {client_dir}\nAvailable: " + ", ".join(p.name for p in CLIENTS_DIR.iterdir() if p.is_dir()))
    cfg = load_config(client_dir)
    th = cfg["thresholds"]
    warnings: list[str] = []

    auto_crm, auto_ads = detect_files(client_dir / "data") if (crm_path is None or ads_path is None) else (None, None)
    crm_path = Path(crm_path) if crm_path else auto_crm
    ads_path = Path(ads_path) if ads_path else auto_ads
    if not crm_path:
        sys.exit(f"CRM file nahi mili. CSV/XLSX daalo: {client_dir / 'data'}")

    clf = Classifier(cfg)
    leads, dupes, raw_count = load_crm(crm_path, clf, cfg, d_from, d_to, warnings)
    if leads.empty:
        sys.exit("CRM me koi lead nahi mili (date filter check karo).")
    if dupes:
        warnings.append(f"{dupes} duplicate leads (same phone) hataye — best status wala rakha.")

    ads = load_ads(ads_path, warnings) if ads_path else None
    if ads is None and spend_override is None:
        warnings.append("Ads file / --spend nahi diya — CPL, CPQL calculate NAHI hue. Spend poochho.")

    total_spend = float(spend_override) if spend_override is not None else (float(ads["spend"].sum()) if ads is not None else 0.0)
    total_ads = None
    if ads is not None and not ads.empty:
        total_ads = {c: float(ads[c].sum()) for c in ("impressions", "link_clicks", "meta_leads")}
    overall = metrics(leads, total_spend, total_ads)
    overall["verdict"], overall["verdict_reason"] = verdict(overall, th)

    # per campaign
    campaigns = []
    aliases = {norm(k): v for k, v in cfg.get("campaign_aliases", {}).items() if not k.startswith("_")}
    leads = leads.assign(ckey=leads["campaign"].map(lambda x: norm(aliases.get(norm(x), x))))
    ads_map = {r["key"]: r for r in ads.to_dict("records")} if ads is not None else {}
    has_campaigns = (leads["campaign"] != "(no campaign in CRM)").any()
    if has_campaigns:
        for ckey, g in leads.groupby("ckey"):
            arow = ads_map.get(ckey)
            m = metrics(g, arow["spend"] if arow else 0.0, arow)
            m["campaign"] = arow["campaign"] if arow else g["campaign"].iloc[0]
            m["matched_in_ads"] = bool(arow)
            m["verdict"], m["verdict_reason"] = verdict(m, th)
            if not arow and ads is not None:
                m["verdict_reason"] += " (Ads file me ye campaign nahi mila — spend 0 maana.)"
            campaigns.append(m)
        campaigns.sort(key=lambda x: x["spend"], reverse=True)
        if ads is not None:
            no_lead = [r for k, r in ads_map.items() if k not in set(leads["ckey"]) and r["spend"] > 0]
            for r in no_lead:
                warnings.append(f"Campaign '{r['campaign']}' ne {fmt_inr(r['spend'])} spend kiya par CRM me 0 leads — naam mismatch ya leads sheet me nahi aaye.")
        if spend_override is not None:
            warnings.append("--spend diya hai: overall CPL usse bana; campaign-level spend Ads file se (agar diya).")

    # per tab (only if >1 tab)
    tabs = []
    if leads["tab"].nunique() > 1:
        for tab, g in leads.groupby("tab"):
            m = metrics(g, 0.0)
            tabs.append({"tab": tab, **{k: m[k] for k in ("leads", "quality", "quality_pct", "site_visits", "visit_ratio_pct", "dead", "followup", "not_called")}})

    # breakdowns
    vc = lambda s: {str(k): int(v) for k, v in s.value_counts().items()}  # noqa: E731
    q_break = vc(leads[leads["bucket"] == "Quality"]["label"])
    d_break = vc(leads[leads["bucket"] == "Dead"]["label"])
    unm = dict(list(vc(leads[leads["bucket"] == "Unmapped"]["status_raw"]).items())[:15])
    if unm:
        warnings.append(f"{overall['unmapped']} leads ka status samajh nahi aaya (list 'unmapped_statuses' me). "
                        "Inhe clients/<client>/config.json -> extra_words me map karo.")
    if total_ads and total_ads["meta_leads"] and abs(total_ads["meta_leads"] - overall["leads"]) > max(5, 0.1 * overall["leads"]):
        warnings.append(f"Meta ne {int(total_ads['meta_leads'])} leads report kiye, CRM me {overall['leads']} — sheet sync / duplicates / date range check karo.")
    if overall["leads"] and overall["not_called"] / overall["leads"] > 0.15:
        warnings.append(f"{overall['not_called']} leads ({pct(overall['not_called'], overall['leads'])}%) abhi tak call nahi hue — sales team ko flag karo.")

    return {
        "client": client,
        "generated_at": dt.datetime.now().strftime("%Y-%m-%d %H:%M"),
        "period": {"from": str(d_from) if d_from else None, "to": str(d_to) if d_to else None},
        "files": {"crm": crm_path.name, "ads": ads_path.name if ads_path else None},
        "raw_rows": raw_count, "duplicates_removed": dupes,
        "thresholds": th,
        "overall": overall,
        "campaigns": campaigns,
        "tabs": tabs,
        "quality_breakdown": q_break,
        "dead_reasons": d_break,
        "unmapped_statuses": unm,
        "warnings": warnings,
    }


