class Classifier:
    def __init__(self, cfg: dict):
        extra = cfg.get("extra_words", {})

        def wrap(words):
            return [r"\b" + re.escape(norm(w)).replace(r"\ ", r"\s+") + r"\b" for w in words if norm(w)]

        self.quality = []
        for key, label, rank, pats in QUALITY_LEVELS:
            self.quality.append((key, label, rank, [re.compile(p) for p in pats + wrap(extra.get(key, []))]))
        self.dead = [(label, [re.compile(p) for p in pats]) for label, pats in DEAD_REASONS]
        if extra.get("dead"):
            self.dead.insert(0, ("Other Dead (client words)", [re.compile(p) for p in wrap(extra["dead"])]))
        self.followup = [re.compile(p) for p in FOLLOWUP_PATTERNS + wrap(extra.get("followup", []))]
        self.negative = [re.compile(p) for p in NEGATIVE_PHRASES]
        self.rewrites = [(re.compile(a), b) for a, b in QUALITY_REWRITES]
        # Where a lead's quality is read from:
        #   "auto"   (default) - Final Status (written by the CAPI script) when filled, else Current Status + Follow-ups
        #   "status" - Current Status + Follow-ups only (ignore Final Status)
        #   "all"    - old rule: Final + Current + Follow-ups + Feedback
        self.source = cfg.get("quality_source", "auto")

    def best_quality(self, text: str):
        cleaned = text
        for rx, rep in self.rewrites:
            cleaned = rx.sub(rep, cleaned)
        for n in self.negative:
            cleaned = n.sub(" ", cleaned)
        for key, label, rank, pats in self.quality:
            if any(p.search(cleaned) for p in pats):
                return key, label, rank
        return None

    def dead_reason(self, text: str):
        for label, pats in self.dead:
            if any(p.search(text) for p in pats):
                return label
        return None

    def has_reason(self, text: str, label: str) -> bool:
        t = norm(text)
        return any(p.search(t) for lab, pats in self.dead if lab == label for p in pats)

    def is_followup(self, text: str) -> bool:
        return any(p.search(text) for p in self.followup)

    def strip_unanswered(self, raw: str) -> str:
        """'Ringing (share details on WhatsApp)' -> 'Ringing': a WhatsApp message to a lead who never picked up is not a
        quality conversation. Works segment by segment (// , | , ; , new line, '/'+date)."""
        if not raw or not WA_SHARE_RX.search(raw):
            return raw
        segs = SEGMENT_SPLIT_RX.split(raw)
        out, changed = [], False
        for seg in segs:
            rest = norm(WA_SHARE_RX.sub(" ", seg)) if seg else ""
            # only when the rest of this note is about an unanswered call ("ringing, sd on ws") — not "sd on ws, budget 90L"
            if seg and WA_SHARE_RX.search(seg) and NO_ANSWER_RX.search(rest) and not self.best_quality(rest) \
                    and len(rest.split()) <= 6:
                seg = WA_SHARE_RX.sub(" ", seg)
                changed = True
            out.append(seg or "")
        return " // ".join(out) if changed else raw

    def strip_brushoff(self, raw: str) -> str:
        """'cb m busy', 'driving cb', 'call back busy in lunch' = the lead brushed the call off — not a quality Call Back.
        A sales 'Call Back' status (or 'call back tomorrow', 'call back post Diwali') still counts."""
        if not raw or not CALLBACK_RX.search(raw) or not BRUSHOFF_RX.search(raw):
            return raw
        out, changed = [], False
        for seg in SEGMENT_SPLIT_RX.split(raw):
            if seg and CALLBACK_RX.search(seg) and BRUSHOFF_RX.search(seg):
                rest = CALLBACK_RX.sub(" ", seg)
                if not self.best_quality(norm(rest)):
                    seg = CALLBACK_RX.sub(" follow up ", seg)
                    changed = True
            out.append(seg or "")
        return " // ".join(out) if changed else raw

    def clean(self, raw: str) -> str:
        return self.strip_brushoff(self.strip_unanswered(raw))

    @staticmethod
    def doubt(feedback: str):
        """Reason why a Quality lead looks doubtful from the Feedback text (or None)."""
        t = norm(feedback)
        if not t:
            return None
        t2 = re.sub(r"\bnot\s+not\b", "not", t)
        for rx, rp in QUALITY_REWRITES:
            t2 = re.sub(rx, rp, t2)
        for rx, label in DOUBT_PHRASES:
            if re.search(rx, t2):
                return label
        return None

    def later_dead(self, latest: str):
        """For a Quality lead: dead reason written in the latest status (e.g. Shared Details -> later Not Interested)."""
        return self.dead_reason(norm(latest)) if latest else None

    def classify(self, final_s: str, current_s: str, followups: list[str], feedback: str):
        """Returns dict(bucket, label, rank, key). Buckets: Quality / Dead / Follow-up / Not Called / Unmapped /
        Duplicate / Test (the last two are removed from totals by the loaders)."""
        final_s, current_s = self.clean(final_s), self.clean(current_s)
        followups = [self.clean(x) for x in followups]
        feedback = self.clean(feedback)
        final_n, current_n = norm(final_s), norm(current_s)
        fu_n = [norm(x) for x in followups]
        fb_n = norm(feedback)
        statuses = [x for x in [final_n, current_n, *fu_n] if x]
        if any(TEST_STATUS_RX.match(x) for x in statuses):
            return {"bucket": "Test", "label": "Test lead", "rank": 0, "key": "test"}
        latest = final_n or current_n or next((x for x in reversed(fu_n) if x), "")
        if latest and DUPLICATE_RX.search(latest) or (not latest and fb_n and DUPLICATE_RX.search(fb_n)):
            return {"bucket": "Duplicate", "label": "Duplicate (marked by sales)", "rank": 0, "key": "duplicate"}
        # 0) CAPI sheets: Final Status already applies "once quality, always quality" -> trust it
        if self.source == "auto" and final_n:
            q = self.best_quality(final_n)
            if q:
                return {"bucket": "Quality", "label": q[1], "rank": q[2], "key": q[0], "source": "final"}
            r = self.dead_reason(final_n)
            if r:
                return {"bucket": "Dead", "label": r, "rank": 0, "key": "dead", "source": "final"}
            if self.is_followup(final_n):
                return {"bucket": "Follow-up", "label": "Follow-up", "rank": 0, "key": "followup", "source": "final"}
            # Final Status not understood -> fall back to Current Status + Follow-ups below
        if self.source == "all":
            everything = " | ".join([final_n, current_n, *fu_n, fb_n])
        elif self.source == "status":
            everything = " | ".join([current_n, *fu_n])
        else:
            everything = " | ".join([final_n, current_n, *fu_n])

        # 1) Quality anywhere in status / follow-ups -> Quality forever (best signal wins)
        q = self.best_quality(everything)
        if q:
            return {"bucket": "Quality", "label": q[1], "rank": q[2], "key": q[0], "source": "status"}
        everything = " | ".join([final_n, current_n, *fu_n, fb_n])

        # 2) Latest status: Final Status > Current Status > last non-empty follow-up
        if latest:
            r = self.dead_reason(latest)
            if r:
                return {"bucket": "Dead", "label": r, "rank": 0, "key": "dead"}
            if self.is_followup(latest):
                return {"bucket": "Follow-up", "label": "Follow-up", "rank": 0, "key": "followup"}
        # 3) Fallback: anything anywhere (latest follow-up first)
        rest = everything.replace("|", " ").strip()
        if not rest:
            return {"bucket": "Not Called", "label": "Not Called", "rank": 0, "key": "not_called"}
        for chunk in [*reversed(fu_n), fb_n, rest]:
            if not chunk:
                continue
            r = self.dead_reason(chunk)
            if r:
                return {"bucket": "Dead", "label": r, "rank": 0, "key": "dead"}
            if self.is_followup(chunk):
                return {"bucket": "Follow-up", "label": "Follow-up", "rank": 0, "key": "followup"}
        return {"bucket": "Unmapped", "label": (final_s or current_s or "").strip() or rest[:40], "rank": 0, "key": "unmapped"}


