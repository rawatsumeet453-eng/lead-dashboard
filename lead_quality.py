# CRM column detection (shared by every report so all of them read a sheet the same way)
# --------------------------------------------------------------------------------------
COARSE_VALUES = {"active", "in active", "inactive", "in followup", "in follow up", "follow up", "followup", "not interested", "visited",
                 "cp", "duplicate leads", "duplicate", "hot", "warm", "cold", "open", "closed", "lost", "won", "junk", "dead", "qualified",
                 "unqualified", "pending", "new"}
STATUS_HDR_EXCLUDE = [r"capi", r"notif", r"whatsapp", r"\bwa\b", r"delivery"]


def detect_crm_columns(df: pd.DataFrame, cfg: dict | None = None) -> dict:
    """Find every column that tells us about a lead. Handles: several status columns (a coarse 'Active / In Active'
    bucket + a detailed status), dated follow-up columns, many feedback columns, unnamed note columns."""
    cfg = cfg or {}
    cols = list(df.columns)
    over = cfg.get("columns", {}) or {}
    is_table = hasattr(df, "rows")

    def raw(c):  # non-empty cell texts of a column (works for a pandas DataFrame or a purekit.Table)
        if is_table:
            return [str(r.get(c, "")).strip() for r in df.rows if str(r.get(c, "")).strip()]
        return [str(v).strip() for v in df[c].dropna().astype(str) if str(v).strip()]

    def vals(c):
        return {norm(v) for v in raw(c) if norm(v)}

    c_final = over.get("final_status") or find_cols(cols, H_FINAL_STATUS)
    status_cols = [c for c in cols if re.search(r"\bstatus\b", norm(c)) and c != c_final
                   and not any(re.search(p, norm(c)) for p in STATUS_HDR_EXCLUDE)]

    def coarse(c):
        v = vals(c)
        return bool(v) and len(v) <= 8 and len(v & COARSE_VALUES) * 2 >= len(v)
    fine = [c for c in status_cols if not coarse(c)]
    crs = [c for c in status_cols if coarse(c)]
    if over.get("current_status"):
        c_curr = over["current_status"]
    else:
        pri = [c for c in fine if re.search(r"^(current\s+)?status$|^lead\s+status$|current\s+status", norm(c))]
        c_curr = (pri or fine or crs or [None])[0]
    extra_status = [c for c in fine + crs if c != c_curr]
    # CAPI columns normally hold a tick/timestamp; if one holds status words (old script / pasted history), read it too
    for c in cols:
        if c in status_cols or c == c_final or not re.search(r"capi", norm(c)):
            continue
        v = raw(c)
        if len(v) >= 3 and sum(not re.match(r"^(✅|☑|✔|true|false|yes|no|sent|done|\d)", x, re.I) for x in v) / len(v) >= 0.3:
            extra_status.append(c)
    used = {c_final, c_curr, *extra_status}
    c_fu = [c for c in find_cols(cols, H_FOLLOWUP, multi=True) if c not in used]
    used |= set(c_fu)
    c_fb = [c for c in find_cols(cols, H_FEEDBACK, multi=True) if c not in used]
    notes = [c for c in cols if c not in used and c not in c_fb
             and (re.fullmatch(r"[\s.\d]*", str(c)) or norm(c).startswith("unnamed"))
             and bool(raw(c))]
    c_camp = find_cols(cols, H_CAMPAIGN)
    c_ad = find_cols(cols, [r"^ad\s+name$", r"^ad$", r"^ads$", r"^ad\s+creative$", r"^creative$", r"^ads?\s+name$"])
    c_phone = find_cols(cols, H_PHONE)
    c_email = find_cols(cols, [r"^e\s?mail$", r"^e\s?mail\s+id$", r"email"])
    c_name = find_cols([c for c in cols if c not in (c_camp, c_ad)], [r"^full\s+name$", r"^name$", r"^lead\s+name$", r"^customer\s+name$", r"^name"])
    c_date = find_cols(cols, H_DATE)
    return {"final": c_final, "current": c_curr, "extra_status": extra_status, "coarse": crs, "followups": c_fu,
            "feedback": c_fb + notes, "notes": notes, "campaign": c_camp, "ad": c_ad, "phone": c_phone, "email": c_email,
            "name": c_name, "date": c_date}


def classify_row(clf: "Classifier", get, cols: dict):
    """Classify one CRM row using detect_crm_columns() output. `get(col)` returns the cell text."""
    fus = [get(c) for c in cols["extra_status"]] + [get(c) for c in cols["followups"]]
    fb = " | ".join(x for x in (get(c) for c in cols["feedback"]) if x)
    final_s, curr_s = get(cols["final"]), get(cols["current"])
    # a coarse bucket ("Active", "Not Interested") must not hide the detailed status as the latest one
    if cols["current"] in cols["coarse"]:
        detailed = next((get(c) for c in cols["extra_status"] if c not in cols["coarse"] and get(c)), "")
        if detailed:
            curr_s, fus = detailed, [curr_s] + [x for x in fus if x != detailed]
    return clf.classify(final_s, curr_s, fus, fb), fus, fb


