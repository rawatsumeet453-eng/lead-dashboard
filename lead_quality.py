def norm(s) -> str:
    if s is None or (isinstance(s, float) and s != s):
        return ""
    s = str(s).lower()
    s = re.sub(r"(\d\s?)(am|pm)(?=[a-z])", r"\1\2 ", s)        # "4.32 pmCall back" -> "pm call back"
    s = re.sub(r"[^a-z0-9]+", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def find_cols(columns, patterns, multi=False):
    """Return first matching column (or all, in sheet order, if multi) for header patterns."""
    normed = [(c, norm(c)) for c in columns]
    if multi:
        out = []
        for c, n in normed:
            if any(re.search(p, n) for p in patterns) and c not in out:
                out.append(c)
        return out
    for p in patterns:  # pattern priority first
        for c, n in normed:
            if re.search(p, n):
                return c
    return None


def deep_merge(base: dict, over: dict) -> dict:
    out = copy.deepcopy(base)
    for k, v in (over or {}).items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = deep_merge(out[k], v)
        else:
            out[k] = v
    return out


def load_config(client_dir: Path) -> dict:
    cfg = json.loads(DEFAULT_CONFIG.read_text(encoding="utf-8"))
    cpath = client_dir / "config.json"
    if cpath.exists():
        cfg = deep_merge(cfg, json.loads(cpath.read_text(encoding="utf-8")))
    return cfg


def read_any(path: Path) -> list[tuple[str, pd.DataFrame]]:
    """Read CSV/TSV/XLSX. Returns list of (tab_name, df). All values as strings."""
    suffix = path.suffix.lower()
    if suffix in (".xlsx", ".xlsm", ".xls"):
        sheets = pd.read_excel(path, sheet_name=None, dtype=str)
        return [(name, df) for name, df in sheets.items() if not df.empty]
    last_err = None
    for enc in ("utf-8-sig", "utf-16", "cp1252", "latin-1"):
        try:
            df = pd.read_csv(path, dtype=str, encoding=enc, sep=None, engine="python")
            if df.shape[1] >= 2:
                return [(path.stem, df)]
        except Exception as e:  # noqa: BLE001
            last_err = e
    raise ValueError(f"Could not read {path.name}: {last_err}")


def to_num(series: pd.Series) -> pd.Series:
    return pd.to_numeric(series.astype(str).str.replace(r"[^0-9.\-]", "", regex=True), errors="coerce").fillna(0.0)


def parse_dates(series: pd.Series, prefer: str = "auto") -> pd.Series:
    """Return naive IST datetimes.
    - Timestamps WITH an offset (+0000 / +05:30 / Z) are converted to IST (CRM sheets often store UTC).
    - Timestamps without offset are taken as IST.
    - Slash dates: day-first vs month-first is auto-detected per column (Meta exports are MM/DD/YYYY,
      Indian sheets DD/MM/YYYY). prefer="dayfirst"/"monthfirst" forces it.
    """
    s = series.fillna("").astype(str).str.strip()
    out = pd.Series(pd.NaT, index=s.index, dtype="datetime64[ns]")
    tz = s.str.contains(r"\d{2}:\d{2}(?::\d{2})?(?:\.\d+)?\s*(?:[+-]\d{2}:?\d{2}|Z)$", regex=True)
    if tz.any():
        d = pd.to_datetime(s[tz], errors="coerce", utc=True, format="mixed")
        out[tz] = d.dt.tz_convert("Asia/Kolkata").dt.tz_localize(None)
    iso = ~tz & s.str.match(r"^\d{4}-\d{2}-\d{2}")
    if iso.any():
        out[iso] = pd.to_datetime(s[iso].str.replace("T", " ", regex=False), errors="coerce", format="mixed")
    rest = ~tz & ~iso & (s != "")
    if rest.any():
        r = s[rest]
        if prefer == "auto":
            parts = r.str.extract(r"^(\d{1,2})[/\-.](\d{1,2})[/\-.]\d{2,4}")
            a, b = pd.to_numeric(parts[0], errors="coerce"), pd.to_numeric(parts[1], errors="coerce")
            prefer = "monthfirst" if ((b > 12).any() and not (a > 12).any()) else "dayfirst"
        out[rest] = pd.to_datetime(r, errors="coerce", dayfirst=(prefer == "dayfirst"), format="mixed")
    return out


