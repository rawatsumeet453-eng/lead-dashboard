def to_markdown(r: dict) -> str:
    o = r["overall"]
    period = f"{r['period']['from'] or 'start'} → {r['period']['to'] or 'latest'}"
    L = [f"# Lead Quality Audit — {r['client']}", "",
         f"Period: {period} | CRM: `{r['files']['crm']}` | Ads: `{r['files']['ads'] or '—'}` | Generated: {r['generated_at']}", "",
         "## Overall", "",
         "| Metric | Value |", "|---|---|",
         f"| Total Leads | {o['leads']} |", f"| Spend | {fmt_inr(o['spend'])} |", f"| CPL | {fmt_inr(o['cpl'])} |",
         f"| Quality Leads | {o['quality']} ({o['quality_pct']}%) |", f"| Cost / Quality Lead | {fmt_inr(o['cost_per_quality_lead'])} |",
         f"| Site Visits (Visited + Booked) | {o['site_visits']} ({o['visit_ratio_pct']}%) |", f"| Will Visit (scheduled) | {o['will_visit']} |",
         f"| Booked | {o['booked']} |", f"| Cost / Visit | {fmt_inr(o['cost_per_visit'])} |",
         f"| Follow-up | {o['followup']} |", f"| Dead | {o['dead']} |", f"| Not Called | {o['not_called']} |", f"| Unmapped | {o['unmapped']} |",
         f"| **Verdict** | **{o['verdict']}** — {o['verdict_reason']} |", ""]
    if o.get("impressions"):
        ctr = f"{o['ctr_pct']}%" if o.get("ctr_pct") is not None else "—"
        L.insert(L.index("| Metric | Value |") + 5, f"| CTR (link) / CPM | {ctr} / {fmt_inr(o['cpm'])} |")
        L.insert(L.index("| Metric | Value |") + 6, f"| Meta-reported leads | {o['meta_leads']} |")
    if r["campaigns"]:
        L += ["## Campaign verdicts", "",
              "| Campaign | Spend | Leads | CPL | Quality % | Visit % | CPQL | CTR | Verdict |", "|---|---|---|---|---|---|---|---|---|"]
        for c in r["campaigns"]:
            ctr = f"{c['ctr_pct']}%" if c.get("ctr_pct") is not None else "—"
            L.append(f"| {c['campaign']} | {fmt_inr(c['spend'])} | {c['leads']} | {fmt_inr(c['cpl'])} | {c['quality_pct']}% | "
                     f"{c['visit_ratio_pct']}% | {fmt_inr(c['cost_per_quality_lead'])} | {ctr} | **{c['verdict']}** |")
        L += ["", "**Reasons:**"] + [f"- {c['campaign']}: {c['verdict_reason']}" for c in r["campaigns"]] + [""]
    if r["tabs"]:
        L += ["## Tab-wise", "", "| Tab | Leads | Quality % | Visits | Visit % | Dead | Follow-up | Not Called |", "|---|---|---|---|---|---|---|---|"]
        for t in r["tabs"]:
            L.append(f"| {t['tab']} | {t['leads']} | {t['quality_pct']}% | {t['site_visits']} | {t['visit_ratio_pct']}% | {t['dead']} | {t['followup']} | {t['not_called']} |")
        L.append("")
    if r["quality_breakdown"]:
        L += ["## Quality breakdown", ""] + [f"- {k}: {v}" for k, v in r["quality_breakdown"].items()] + [""]
    if r["dead_reasons"]:
        L += ["## Dead reasons", ""] + [f"- {k}: {v}" for k, v in sorted(r["dead_reasons"].items(), key=lambda x: -x[1])] + [""]
    if r["unmapped_statuses"]:
        L += ["## Unmapped statuses (config.json me map karo)", ""] + [f"- `{k}`: {v}" for k, v in r["unmapped_statuses"].items()] + [""]
    if r["warnings"]:
        L += ["## Data warnings", ""] + [f"- {w}" for w in r["warnings"]] + [""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser(description="Lead quality audit for one client")
    ap.add_argument("--client", required=True, help="folder name under clients/")
    ap.add_argument("--crm", help="CRM CSV/XLSX path (default: newest in data/)")
    ap.add_argument("--ads", help="Ads Manager CSV/XLSX path (default: newest in data/)")
    ap.add_argument("--spend", type=float, help="Total spend override (if no Ads file)")
    ap.add_argument("--from", dest="d_from", type=dt.date.fromisoformat, help="YYYY-MM-DD")
    ap.add_argument("--to", dest="d_to", type=dt.date.fromisoformat, help="YYYY-MM-DD (inclusive)")
    ap.add_argument("--out", help="output dir (default: clients/<client>/reports)")
    ap.add_argument("--quiet", action="store_true")
    a = ap.parse_args()

    report = build(a.client, a.crm, a.ads, a.spend, a.d_from, a.d_to)
    out_dir = Path(a.out) if a.out else CLIENTS_DIR / a.client / "reports"
    out_dir.mkdir(parents=True, exist_ok=True)
    stamp = dt.date.today().isoformat()
    (out_dir / f"{stamp}_audit.json").write_text(json.dumps(report, indent=2, ensure_ascii=False, default=str), encoding="utf-8")
    md = to_markdown(report)
    (out_dir / f"{stamp}_audit.md").write_text(md, encoding="utf-8")
    if not a.quiet:
        sys.stdout.reconfigure(encoding="utf-8")
        print(md)
        print(f"\nSaved: {out_dir / (stamp + '_audit.json')}")


if __name__ == "__main__":
    main()
