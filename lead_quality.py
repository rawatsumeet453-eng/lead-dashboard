def detect_files(data_dir: Path):
    crm, ads = [], []
    for f in sorted(data_dir.glob("*"), key=lambda p: p.stat().st_mtime, reverse=True):
        if f.suffix.lower() not in (".csv", ".tsv", ".txt", ".xlsx", ".xlsm", ".xls") or f.name.startswith("~$"):
            continue
        try:
            tabs = read_any(f)
        except Exception:  # noqa: BLE001
            continue
        cols = [c for _, df in tabs for c in df.columns]
        ncols = {norm(c) for c in cols}
        if ncols & {"form id", "form name", "is organic"}:
            continue  # Meta lead download — not a CRM (its lead_status is always "complete")
        if find_cols(cols, A_SPEND) and find_cols(cols, A_CAMPAIGN):
            ads.append(f)
        elif find_cols(cols, H_FINAL_STATUS + H_CURRENT_STATUS) and (find_cols(cols, H_PHONE) or find_cols(cols, [r"email"])):
            crm.append(f)
    return (crm[0] if crm else None), (ads[0] if ads else None)


def load_crm(path: Path, clf: Classifier, cfg: dict, d_from, d_to, warnings: list):
    rows = []
    n_dup = n_test = 0
    for tab, df in read_any(path):
        df = df.dropna(how="all")
        cols = detect_crm_columns(df, cfg)
        if not (cols["final"] or cols["current"]) or not (cols["phone"] or cols["email"] or cols["name"]):
            continue
        dates = parse_dates(df[cols["date"]]) if cols["date"] else pd.Series([pd.NaT] * len(df), index=df.index)
        for idx, r in df.iterrows():
            get = lambda c: ("" if c is None or pd.isna(r.get(c)) else str(r.get(c)).strip())  # noqa: E731
            if is_test_lead(get(cols["name"]), get(cols["email"]), get(cols["phone"])):
                n_test += 1
                continue
            if not any(get(c) for c in (cols["name"], cols["email"], cols["phone"]) if c):
                continue  # no person on this row (blank / only campaign name)
            res, _, _ = classify_row(clf, get, cols)
            if res["bucket"] in ("Duplicate", "Test"):
                n_dup += res["bucket"] == "Duplicate"
                n_test += res["bucket"] == "Test"
                continue
            rows.append({
                "email": clean_email(get(cols["email"])),
                "tab": tab,
                "campaign": get(cols["campaign"]) or "(no campaign in CRM)",
                "phone10": clean_phone(get(cols["phone"])) if cols["phone"] else "",
                "date": dates.get(idx),
                "status_raw": get(cols["final"]) or get(cols["current"]),
                **res,
            })
        warnings.append(f"Tab '{tab}': columns used -> " + json.dumps({k: v for k, v in cols.items() if v}, ensure_ascii=False))
        if not cols["campaign"]:
            warnings.append(f"Tab '{tab}': CRM me campaign column nahi hai — per-campaign quality possible nahi, sirf overall.")
    if n_dup:
        warnings.append(f"{n_dup} leads sales team ne 'Duplicate / Repeat' mark kiye — total se hata diye.")
    if n_test:
        warnings.append(f"{n_test} test leads hata diye.")

    leads = pd.DataFrame(rows)
    if leads.empty:
        return leads, 0, 0

    # date filter
    if d_from or d_to:
        has_date = leads["date"].notna()
        if not has_date.any():
            warnings.append("Date filter diya par CRM me date column parse nahi hua — filter apply NAHI hua.")
        else:
            mask = has_date.copy()
            if d_from:
                mask &= leads["date"] >= pd.Timestamp(d_from)
            if d_to:
                mask &= leads["date"] < pd.Timestamp(d_to) + pd.Timedelta(days=1)
            dropped_nodate = int((~has_date).sum())
            if dropped_nodate:
                warnings.append(f"{dropped_nodate} leads ki date blank/invalid — date filter me exclude hue.")
            leads = leads[mask]

    # dedupe by phone (keep the best-classified copy)
    dupes = 0
    if cfg.get("dedupe_by_phone", True):
        leads, dupes = dedupe_leads(leads)
    return leads, dupes, len(rows)


def dedupe_leads(leads: pd.DataFrame):
    """Same person = same REAL phone (10 digits) OR same email. Keeps the best-classified copy.
    Scientific-notation phones are ignored (they make different people look identical)."""
    if leads.empty:
        return leads, 0
    bucket_order = {"Quality": 4, "Follow-up": 2, "Unmapped": 1, "Not Called": 1, "Dead": 0}
    df = leads.assign(_b=leads["bucket"].map(bucket_order), _r=leads["rank"]).sort_values(["_b", "_r"], ascending=False)
    seen_p, seen_e, keep = set(), set(), []
    for idx, r in df.iterrows():
        p, e = r.get("phone10", ""), r.get("email", "")
        if (p and p in seen_p) or (e and e in seen_e):
            continue
        keep.append(idx)
        if p:
            seen_p.add(p)
        if e:
            seen_e.add(e)
    out = df.loc[keep].drop(columns=["_b", "_r"]).sort_index()
    return out, len(df) - len(out)


def load_ads(path: Path, warnings: list):
    frames = []
    for tab, df in read_any(path):
        cols = list(df.columns)
        c_camp, c_spend = find_cols(cols, A_CAMPAIGN), find_cols(cols, A_SPEND)
        if not (c_camp and c_spend):
            continue
        out = pd.DataFrame({
            "campaign": df[c_camp].fillna("").astype(str).str.strip(),
            "spend": to_num(df[c_spend]),
            "impressions": to_num(df[find_cols(cols, A_IMPR)]) if find_cols(cols, A_IMPR) else 0.0,
            "link_clicks": to_num(df[find_cols(cols, A_LINK_CLICKS) or find_cols(cols, A_ALL_CLICKS)])
            if (find_cols(cols, A_LINK_CLICKS) or find_cols(cols, A_ALL_CLICKS)) else 0.0,
            "meta_leads": to_num(df[find_cols(cols, A_LEADS)]) if find_cols(cols, A_LEADS) else 0.0,
        })
        frames.append(out[out["campaign"] != ""])
    if not frames:
        warnings.append(f"Ads file '{path.name}' me Campaign name + Amount spent columns nahi mile.")
        return pd.DataFrame(columns=["campaign", "spend", "impressions", "link_clicks", "meta_leads"])
    ads = pd.concat(frames)
    ads["key"] = ads["campaign"].map(norm)  # CRM names are mapped onto Ads names via campaign_aliases
    return ads.groupby("key", as_index=False).agg(
        campaign=("campaign", "first"), spend=("spend", "sum"), impressions=("impressions", "sum"),
        link_clicks=("link_clicks", "sum"), meta_leads=("meta_leads", "sum"))


